// Shared spectacle and sprite calibration — run with node tests/arena-combat-feel.js
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
require('../public/arena-motion');
require('../public/arena-focus');
require('../public/arena-combat-feel');
require('../public/practice-scale-published');
const scales=require('../public/practice-scale-profiles');
require('../public/ludus-practice');
const feel=globalThis.ArenaCombatFeel,practice=globalThis.LudusPractice.rules;
const fighter=(x,face)=>({x,face,hp:150,maxHp:150,dead:false});
const source=fighter(410,1),target=fighter(600,-1);
const state={flash:0,fx:true};
assert(feel.event(state,'parry',source,target,0,{team:true}));
assert(state.cameraKick&&state.cinematic,'shake and cinematic both start');
assert(source.bodySpring&&target.bodySpring,'both bodies rebound');
assert(target.hitVisual,'victim receives transient scale pulse');
const dt=feel.advance(state,[source,target],.04);
assert(dt<.04,'focus slows combat simulation without freezing effects');
const camera=feel.sample(state,{team:true});
assert(camera.zoom>=1&&camera.zoom<=1.12&&camera.flash>0,'bounded team camera and flash');
assert.equal(feel.sample(state,{team:true,reduced:true}).flash,0,'reduced-motion fallback');
assert.equal(practice.deathFrame({deathAt:13},13),0,'death begins at first frame');
assert.equal(practice.deathFrame({deathAt:13},13.45),4,'death plays forwards once');
for(const clock of [13.70,14,23,1000])assert.equal(practice.deathFrame({deathAt:13},clock),7,'corpse holds final frame');
const look='murmillo_champion_red';
const published=scales.scale(look);
const nominal=scales.cellPixels(look,600,600,202);
const trimmed=scales.framePixels(look,150,202);
assert(Math.abs(nominal-202/600*published)<1e-8,'matches untrimmed normal-duel cell');
assert(trimmed>nominal*3.9,'former trimmed-pose oversizing is eliminated');
const html=fs.readFileSync(path.join(__dirname,'../public/index.html'),'utf8');
assert(html.includes('practiceNominal:(unit)=>'),'bridge exposes the original source-cell dimensions');
assert(html.includes('arena-combat-feel.js?'),'all arenas load shared spectacle');
assert(html.includes('authored.scale*contactZoom'),'1v1 hit scaling restored');
console.log('PASS: shared spectacle, 1v1 impact, untrimmed sprite scale, final-frame champion defeat and reduced-motion fallback.');
