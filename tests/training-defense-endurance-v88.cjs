const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const {ArenaBalance:bal}=(()=>{globalThis.ArenaBalance=null;require('../public/arena-balance.js');return globalThis;})();
const R=require('../public/ludus-training-risk.js');
const base={atk:20,hp:150,move:240,sp:40};
const h={cls:'murmillo',stats:{str:2,agi:2,def:3,end:3,focus:2},birthStats:{str:4,agi:4,end:4,focus:4}};
const before=bal.heroStats(h,base);
h.stats.def+=3;const defense=bal.heroStats(h,base);
assert(defense.armor>before.armor);assert.equal(defense.hp,before.hp,'DEF training must not add HP');
h.stats.def-=3;h.stats.end+=3;const endurance=bal.heroStats(h,base);
assert(endurance.hp>before.hp);assert.equal(endurance.armor,before.armor,'END training must not add armor');
assert.equal(R.KEYS.length,5);
for(const k of ['str','agi','def','end','focus'])assert(R.KEYS.includes(k));
const test={birthStats:{end:7},aptitudes:{end:1.3},trainingAttempts:{def:3,end:7}};
assert.equal(R.quote(test,'def').attempts,3);assert.equal(R.quote(test,'end').attempts,7);
assert.equal(bal.trainingAptitude(test,'def'),bal.trainingAptitude(test,'end'));
const index=read('public/index.html');
assert.match(index,/if\(!Object\.prototype\.hasOwnProperty\.call\(h\.stats,'def'\)\)/,'legacy saved training migration exists');
assert.match(index,/changedDefenseStats\)saveCareer\(\)/,'migration persists');
assert.match(index,/stats:\{str:Math\.max\(0,attrs\[0\]-3\),agi:Math\.max\(0,attrs\[1\]-3\),def:/,'newly hired gladiators start with DEF');
console.log('PASS: defense-only armor, endurance-only HP, independent training risk, backward-compatible saved fighters');
