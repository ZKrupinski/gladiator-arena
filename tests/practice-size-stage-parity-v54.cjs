'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const win={};
vm.runInNewContext(fs.readFileSync('public/tools/practice-size-stage.js','utf8'),{window:win,console});
const stage=win.SpartacusStagePreview;
assert(stage,'size stage is exported');
const close=(a,b,message)=>assert(Math.abs(a-b)<1e-8,message+': '+a+' != '+b);
const source=(w,h,pivotX=w/2,footY=h)=>({canvas:{width:w,height:h},pivotX,footY});
const champion=source(960,540,480,516);
const duelChampion=stage.rect({key:'murmillo_champion_red',frame:champion,scene:'duel',zoom:.75,scale:1.16});
close(duelChampion.w,960*(348*.82)/540*.75*1.16,'red champion actual 1v1 body');
close(duelChampion.pivotY,516*(348*.82)/540*.75*1.16,'red champion planted foot');
const practiceChampion=stage.rect({key:'murmillo_champion_red',frame:champion,scene:'practice',zoom:.75,scale:1.16});
close(practiceChampion.w,960*202/540*.75*1.16,'red champion actual practice body');
assert(duelChampion.w>practiceChampion.w*1.4,'tool must not display both champion views at 202px');
const growth={...source(350,410,170,397),cellWidth:362,cellHeight:362};
const duelGrowth=stage.rect({key:'thraex_a_L5',frame:growth,scene:'duel',zoom:.75,scale:1.083});
close(duelGrowth.h,410*(348*.82)/362*.75*1.083,'growth uses source CELL size, not cropped alpha frame');
const wrong=410*202/410*.75*1.083;
assert(Math.abs(duelGrowth.h-wrong)>30,'the old thumbnail scale must differ from real duel');
const beast=source(512,512,256,480);
const wolf=stage.rect({key:'beast_wolf',frame:beast,scene:'duel',zoom:.75,scale:1.344725});
close(wolf.h,348*.83*.75*1.344725,'beast keeps duel ink ratio');
close(stage.offsetFactor('beast_wolf','duel'),1,'beast action XY not human projected');
close(stage.offsetFactor('npc_carnifex','duel'),1,'executioner action XY not human projected');
close(stage.offsetFactor('thraex_a_L5','duel'),(348*.82)/202,'human duel position projected once');
const calls=[],fakeCtx={save(){},restore(){},translate(){},scale(){},
 drawImage(...args){calls.push(args)}};
const drawn=stage.draw(fakeCtx,{key:'murmillo_champion_red',frame:champion,scene:'duel',
 x:160,y:370,zoom:.64,scale:1.16,foot:0});
close(drawn.ground,370,'the same ground line is preserved for all compared looks');
assert.equal(calls.length,1,'comparison draws unaltered source once');
close(calls[0][3],960*(348*.82)/540*.64*1.16,'comparison calls real source pixel width');
const studio=fs.readFileSync('public/tools/practice-scale-calibrator.html','utf8');
assert(studio.includes('id="compareCanvas"')&&studio.includes('id="compareScale"'));
assert(studio.includes('id="compareKey"')&&studio.includes('id="scaleScene"'));
assert(studio.includes('setupCompareEditor();initActionEditor();build();'));
assert.match(studio,/frame,idle:frame,scene:\$\('#scaleScene'\)\.value/);
assert.match(studio,/cellWidth:atlas\.cellWidth,cellHeight:atlas\.cellHeight/);
assert.match(studio,/function renderComparison\(\)/);
assert.match(studio,/persistScaleEdit\(\)/,'live comparison edits autosave');
const scripts=[...studio.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
const inline=scripts.map(x=>x[1]).find(x=>x.includes('setupCompareEditor();initActionEditor();build();'));
assert(inline);
new vm.Script(inline);
console.log('PASS: actual duel/practice proportions, champion/growth/beast pixels, common foot anchors, interactive stage');
