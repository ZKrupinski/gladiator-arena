'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const profileSource=fs.readFileSync('public/practice-scale-profiles.js','utf8');
const cells=new Map();
const storage={getItem:key=>cells.get(key)||null,setItem:(key,val)=>cells.set(key,val),removeItem:key=>cells.delete(key)};
function load(scales={},feet={}){
 const win={SpartacusPublishedScales:scales,SpartacusPublishedFeet:feet,localStorage:storage};
 vm.runInNewContext(profileSource,{window:win,console});
 return win.PracticeScaleProfiles;
}
let p=load();
assert.equal(Object.keys(p.FOOT_DEFAULTS).length,31);
assert.equal(p.foot('beast_wolf'),0);
assert.equal(p.foot('npc_carnifex'),0);
assert.equal(p.clampFoot(-200),-70);
assert.equal(p.clampFoot(200),40);
p.write({beast_wolf:1.33});
p.writeFeet({beast_wolf:-22,npc_carnifex:15});
p=load();
assert.equal(p.scale('beast_wolf'),1.33);
assert.equal(p.foot('beast_wolf'),-22);
assert.equal(p.foot('npc_carnifex'),15);
assert.equal(p.foot('beast_lion'),0);
p=load({}, {beast_wolf:11});
assert.equal(p.foot('beast_wolf'),11,'new published Y invalidates stale device draft');
assert.equal(p.scale('beast_wolf'),1.33,'foot-only default update does not reset size draft');
p.writeFeet({beast_wolf:-30});
assert.equal(load({}, {beast_wolf:11}).foot('beast_wolf'),-30);
p=load({}, {beast_wolf:-40});
assert.equal(p.foot('beast_wolf'),-40);
p.resetFeet();
assert.equal(p.foot('beast_wolf'),-40);
assert.equal(p.scale('beast_wolf'),1.33,'reset feet does not erase size');
const html=fs.readFileSync('public/tools/practice-scale-calibrator.html','utf8');
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)]
 .map(x=>x[1]).find(x=>x.includes('SpartacusScaleStudio'));
assert.ok(inline,'studio inline script present');
new vm.Script(inline,{filename:'practice-scale-calibrator.inline.js'});
assert.match(inline,/footSlider\.addEventListener\('input'/);
assert.match(inline,/bulkFootMinus/);
assert.match(inline,/bulkFootPlus/);
assert.match(inline,/bulkFootReset/);
assert.match(inline,/footOffsets:feet/);
assert.match(inline,/p\.writeFeet\(feet\)/);
const publisher=fs.readFileSync('public/tools/practice-scale-publish.js','utf8');
new vm.Script(publisher);
assert.match(publisher,/SpartacusPublishedFeet=Object\.freeze/);
assert.match(publisher,/feet:studio\(\)\?\.feet/);
assert.match(publisher,/저장 발높이가 올바르지 않습니다/);
const runtime=fs.readFileSync('public/ludus-practice.js','utf8');
assert.match(runtime,/ctx\.translate\(0,profilesFoot\(unit\)\*scale\)/);
const beast=fs.readFileSync('public/arena-beasts.js','utf8');
assert.match(beast,/ctx\.translate\(cx,ground\+foot\)/);
const carnifex=fs.readFileSync('public/arena-carnifex.js','utf8');
assert.match(carnifex,/floorY\+bootOffset/);
const saved=fs.readFileSync('public/practice-scale-published.js','utf8');
assert.match(saved,/SpartacusPublishedFeet=Object\.freeze/);
const index=fs.readFileSync('public/index.html','utf8');
for(const asset of ['practice-scale-published','practice-scale-profiles','arena-beasts'])
 assert.match(index,new RegExp(asset+'\\.js\\?v=foot-height-v42'),'current foot editor asset version');
assert.ok(index.includes('ludus-practice.js?v=native-frame-scale-v45'),'practice v45 cache invalidation');
assert.ok(index.includes('arena-carnifex.js?v=carnifex-projection-v44'),'existing executioner projection cache');
assert.match(index,/function duelFootOffset\(f\)/,'regular duel uses calibration key');
assert.match(index,/const footOffset=duelFootOffset\(f\)/,'regular duel stores per-look Y offset');
assert.match(index,/if\(!f\.beastType\)y\+=footOffset/,'regular duel renders all human actions at approved foot height');
assert.match(index,/\(motionExtra\?\.y\|\|0\)\+footOffset/,'combat VFX rendering follows the moved fighter');
console.log('PASS: 31 foot controls, isolated device save, released defaults, live rendering hooks, publisher, cache versions');
